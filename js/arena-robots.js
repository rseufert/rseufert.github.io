        "  je sit",
        "  opo throttle, 70",
        "  ret",
        ":sit",
        "  opo throttle, 0",
        "  ret",
        "",
        ":clock                  ; every 300 ticks, score the spell and choose",
        "  int @timer",
        "  sub ax, [3]",
        "  cmp ax, 300",
        "  jl done",
        "  ipo damage, ax",
        "  sub ax, [4]           ; damage taken this spell",
        "  cmp [5], 0",
        "  jne drove",
        "  add [6], ax",
        "  add [7], 1",
        "  jmp choose",
        ":drove",
        "  add [8], ax",
        "  add [9], 1",
        ":choose",
        "  add [10], 1",
        "  mov ax, [10]",
        "  mod ax, 4",
        "  cmp ax, 0",
        "  jne compare",
